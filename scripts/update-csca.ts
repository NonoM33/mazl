// Builds data/csca/csca.pem (+ README.md) from the German BSI CSCA master list.
//
//   bun scripts/update-csca.ts [--url <url>] [--file <path.ml|.zip>] [--pin-root <sha256>] [--no-pin] [--out <dir>]
//
// Default pin: the SHA-256 fingerprints BSI publishes for CSCA Germany
// (https://www.bsi.bund.de/DE/Themen/Oeffentliche-Verwaltung/Elektronische-Identitaeten/
// Public-Key-Infrastrukturen/CSCA/Root_Cert_Germany/Root_Certificate_node.html,
// read 2026-10-23: certificate 10/2024). BSI plans the next root change for 2027:
// the script then fails with "does not match a pinned fingerprint"; read the new
// value on that page, add it below, and re-run.
//
// The master list is a CMS SignedData (ICAO 9303 Part 12) listing the CSCA
// certificates of many states. We verify its signature, the validity of the
// list signer, and that the signer chains to a self-signed CSCA contained in
// the list, and that this root has a fingerprint pinned below (--no-pin turns
// that off: the root is then trusted on first use over TLS).
import { createHash } from "node:crypto";
import { mkdir } from "node:fs/promises";
import { join } from "node:path";
import { readMasterList, countryOf, toPem } from "../src/features/verification/infra/master-list";
import { NodeChipCrypto } from "../src/features/verification/infra/node-chip-crypto";
import { readZip } from "../src/features/verification/infra/zip-reader";

const DEFAULT_URL = "https://www.bsi.bund.de/SharedDocs/Downloads/DE/BSI/ElekAusweise/CSCA/GermanMasterList.zip?__blob=publicationFile";
const PINNED_ROOTS: readonly string[] = [
  "2084aed7a991b3158e63ad750d3dc38bc6c9dcf5958f28d1162f49884e91ada8", // self-signed CSCA Germany, 10/2024
  "5f28cb692fb346ba2d23674c8778f2810c24a35869e5b517de3abd67d5db20bd", // link certificate, 10/2024
];
const sha256 = (bytes: Uint8Array): string => createHash("sha256").update(bytes).digest("hex");

function option(name: string): string | undefined {
  const at = process.argv.indexOf(name);
  return at >= 0 ? process.argv[at + 1] : undefined;
}

async function fetchBytes(url: string): Promise<Uint8Array> {
  const response = await fetch(url, { signal: AbortSignal.timeout(60_000) });
  if (!response.ok) throw new Error(`download failed: HTTP ${response.status} for ${url}`);
  return new Uint8Array(await response.arrayBuffer());
}

function pinnedRoots(): readonly string[] {
  if (process.argv.includes("--no-pin")) return [];
  const extra = option("--pin-root");
  return extra ? [...PINNED_ROOTS, extra] : PINNED_ROOTS;
}

function isZip(bytes: Uint8Array): boolean {
  return bytes[0] === 0x50 && bytes[1] === 0x4b;
}

async function loadMasterList(): Promise<{ name: string; der: Uint8Array; source: string }> {
  const file = option("--file");
  const url = option("--url") ?? process.env.CSCA_MASTERLIST_URL ?? DEFAULT_URL;
  const source = file ?? url;
  const raw = file ? new Uint8Array(await Bun.file(file).arrayBuffer()) : await fetchBytes(url);
  if (!isZip(raw)) return { name: file?.split("/").pop() ?? "masterlist.ml", der: raw, source };
  const entry = readZip(raw).find((e) => e.name.toLowerCase().endsWith(".ml"));
  if (!entry) throw new Error("no .ml file in the archive");
  return { name: entry.name, der: entry.data, source };
}

function readme(opts: {
  source: string;
  name: string;
  listSha: string;
  bundleSha: string;
  total: number;
  unreadable: number;
  signer: string;
  root: string;
  pinned: boolean;
  perCountry: ReadonlyArray<readonly [string, number]>;
  today: string;
}): string {
  const rows = opts.perCountry.map(([c, n]) => `| ${c} | ${n} |`).join("\n");
  return `# CSCA trust store

Generated by \`bun scripts/update-csca.ts\` on ${opts.today}. Do not edit by hand.

| | |
|---|---|
| Source | ${opts.source} |
| Master list file | \`${opts.name}\` |
| Master list SHA-256 | \`${opts.listSha}\` |
| \`csca.pem\` SHA-256 | \`${opts.bundleSha}\` |
| Certificates | ${opts.total} (${opts.perCountry.length} countries, ${opts.unreadable} unreadable skipped) |
| List signer | \`${opts.signer}\` |
| Issuing root CSCA SHA-256 | \`${opts.root}\` (${opts.pinned ? "matches the fingerprint published by BSI on its CSCA Germany page" : "trusted on first use: compare with the value published by BSI"}) |

Verified before writing: CMS signature of the list, validity of the signer
certificate, chain from the signer to a self-signed CSCA contained in the list.
The bundle also holds link certificates; validity periods are checked at
verification time, not here. Revocation is not covered.

## Certificates per country (ISO 3166 alpha-2, as in the subject)

| Country | CSCA certificates |
|---|---|
${rows}
`;
}

async function main(): Promise<void> {
  const out = option("--out") ?? "data/csca";
  const { name, der, source } = await loadMasterList();
  const ml = readMasterList(der, new NodeChipCrypto(), { now: new Date(), pinnedRoots: pinnedRoots() });
  const sorted = [...ml.certificates].sort((a, b) => countryOf(a).localeCompare(countryOf(b)) || a.subject.localeCompare(b.subject) || a.notBefore.getTime() - b.notBefore.getTime());
  const bundle = sorted.map((c) => `# ${countryOf(c)} sha256=${sha256(c.der)} notAfter=${c.notAfter.toISOString().slice(0, 10)}\n${toPem(c.der)}`).join("\n");
  const counts = new Map<string, number>();
  for (const c of sorted) counts.set(countryOf(c), (counts.get(countryOf(c)) ?? 0) + 1);
  await mkdir(out, { recursive: true });
  await Bun.write(join(out, "csca.pem"), bundle);
  await Bun.write(
    join(out, "README.md"),
    readme({
      source,
      name,
      listSha: sha256(der),
      bundleSha: sha256(new TextEncoder().encode(bundle)),
      total: sorted.length,
      unreadable: ml.unreadable,
      signer: ml.signerSubject,
      root: ml.rootSha256,
      pinned: ml.pinned,
      perCountry: [...counts.entries()].sort(([a], [b]) => a.localeCompare(b)),
      today: new Date().toISOString().slice(0, 10),
    }),
  );
  console.log(`wrote ${sorted.length} CSCA certificates from ${counts.size} countries to ${out}/csca.pem (FRA: ${counts.get("FR") ?? 0})`);
}

main().catch((e: unknown) => {
  console.error(e instanceof Error ? `${e.name}: ${e.message}` : e);
  process.exit(1);
});
